/** Moves one record through the state machine, refusing illegal transitions. */
export async function updateQueueState(
  queueRecordId: string,
  to: QueueState,
  now: string,
  patch: Partial<Pick<QueuedSale, "lastErrorCode" | "lastErrorMessage" | "nextAttemptAt">> = {}
): Promise<QueueResult<QueuedSale>> {
  return withDb(async (db) => {
    const raw = await readQueuedSaleRecord(db, queueRecordId);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };
    if (raw.value === null) return { ok: false, reason: "not_found" };

    const parsed = readQueuedSale(raw.value);

    if (!parsed.ok) return { ok: false, reason: "corrupt_record" };

    const moved = transitionQueuedSale(parsed.record, to, now, patch);

    if (!moved.ok) return { ok: false, reason: "illegal_transition" };

    const written = await putQueuedSale(db, moved.record);

    return written.ok ? { ok: true, value: moved.record } : { ok: false, reason: "write_failed" };
  });
}

/** Increments the attempt counter. Kept separate so a transition cannot reset it. */
/**
 * Feature 24.5F — applies beginOperatorRetry to a stored record.
 *
 * Goes through the same read-parse-transition-write shape updateQueueState uses,
 * rather than exposing raw storage to a caller: the transition is still checked,
 * a corrupt record is still refused, and there is still exactly one module that
 * writes the queue. updateQueueState itself cannot serve here because its patch
 * deliberately covers only the error metadata, and this must also reset the
 * attempt counter.
 */
export async function startOperatorRetry(
  queueRecordId: string,
  now: string
): Promise<QueueResult<QueuedSale>> {
  return withDb(async (db) => {
    const raw = await readQueuedSaleRecord(db, queueRecordId);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };
    if (raw.value === null) return { ok: false, reason: "not_found" };

    const parsed = readQueuedSale(raw.value);

    if (!parsed.ok) return { ok: false, reason: "corrupt_record" };

    const moved = beginOperatorRetry(parsed.record, now);

    if (!moved.ok) return { ok: false, reason: "illegal_transition" };

    const written = await putQueuedSale(db, moved.record);

    return written.ok ? { ok: true, value: moved.record } : { ok: false, reason: "write_failed" };
  });
}

export async function markAttempt(
  queueRecordId: string,
  now: string
): Promise<QueueResult<QueuedSale>> {
  return withDb(async (db) => {
    const raw = await readQueuedSaleRecord(db, queueRecordId);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };
    if (raw.value === null) return { ok: false, reason: "not_found" };

    const parsed = readQueuedSale(raw.value);

    if (!parsed.ok) return { ok: false, reason: "corrupt_record" };

    const marked = markQueuedSaleAttempt(parsed.record, now);
    const written = await putQueuedSale(db, marked);

    return written.ok ? { ok: true, value: marked } : { ok: false, reason: "write_failed" };
  });
}

/**
 * Removes ONE synced record.
 *
 * Guarded on state deliberately: only a sale the server has confirmed may be
 * removed from this device. Anything else is still the only copy of money that
 * changed hands, and deleting it would be the worst bug this feature could
 * ship. There is no bulk delete and no "clear queue" anywhere in this module.
 */
export async function deleteSyncedSale(queueRecordId: string): Promise<QueueResult<void>> {
  return withDb(async (db) => {
    const raw = await readQueuedSaleRecord(db, queueRecordId);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };
    if (raw.value === null) return { ok: false, reason: "not_found" };

    const parsed = readQueuedSale(raw.value);

    if (!parsed.ok) return { ok: false, reason: "corrupt_record" };
    if (parsed.record.state !== "synced") return { ok: false, reason: "illegal_transition" };

    const deleted = await deleteQueuedSaleRecord(db, queueRecordId);

    return deleted.ok ? { ok: true, value: undefined } : { ok: false, reason: "write_failed" };
  });
}

