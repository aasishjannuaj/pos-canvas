export type QueueListing = {
  sales: QueuedSale[];
  /** Records that failed validation. Never silently dropped — see below. */
  quarantined: QuarantinedSale[];
};

/**
 * Every queued sale, FIFO, with unreadable records reported alongside.
 *
 * A corrupt record is NOT skipped quietly. It is money someone took, and the
 * only honest thing a reader can do is say "there is a row here I cannot
 * understand". 24.5D turns each of these into a needs_attention item for the
 * owner rather than deleting it.
 */
export async function listQueuedSales(): Promise<QueueResult<QueueListing>> {
  return withDb(async (db) => {
    const raw = await readAllQueuedSaleRecords(db);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };

    const sales: QueuedSale[] = [];
    const quarantined: QuarantinedSale[] = [];

    for (const entry of raw.value) {
      const parsed = readQueuedSale(entry);

      if (parsed.ok) {
        sales.push(parsed.record);
        continue;
      }

      const id =
        entry !== null && typeof entry === "object" && !Array.isArray(entry)
          ? ((entry as Record<string, unknown>).queueRecordId as string | undefined) ?? null
          : null;

      quarantined.push({ queueRecordId: id, reason: parsed.reason });
    }

    return { ok: true, value: { sales: sortQueueFifo(sales), quarantined } };
  });
}

/** The FIFO work list a sync engine will drain. */
export async function listPendingSales(): Promise<QueueResult<QueuedSale[]>> {
  const listing = await listQueuedSales();

  return listing.ok
    ? { ok: true, value: listing.value.sales.filter((sale) => sale.state === "pending") }
    : listing;
}

/**
 * Feature 24.5D — pending sales whose backoff window has elapsed, FIFO.
 *
 * A record still inside its window is skipped, not reordered: it keeps its
 * place in the queue and simply is not eligible yet. That is what lets one
 * failing sale back off without holding up the sales behind it.
 */
export async function listDueSales(
  now: number,
  /**
   * Feature 24.5F — a manual press may skip a pending backoff, and nothing else
   * may. Defaults to false so every automatic caller keeps the old behaviour
   * without knowing this parameter exists.
   */
  options: { ignoreBackoff?: boolean } = {}
): Promise<QueueResult<QueuedSale[]>> {
  const listing = await listQueuedSales();
  const due = options.ignoreBackoff === true
    ? (sale: QueuedSale) => isManuallyRetryable(sale)
    : (sale: QueuedSale) => isDueForAttempt(sale, now);

  return listing.ok ? { ok: true, value: listing.value.sales.filter(due) } : listing;
}

/**
 * Feature 24.5D — records the server's identity for a synced sale.
 *
 * The state change and the order identity are written TOGETHER, so a record can
 * never be `synced` without the order number that proves it. Retry metadata is
 * normalised at the same time: there is nothing left to retry.
 */
export async function markSynced(
  queueRecordId: string,
  receipt: { orderId: string; orderNumber: string; createdAt: string | null },
  now: string
): Promise<QueueResult<QueuedSale>> {
  return withDb(async (db) => {
    const raw = await readQueuedSaleRecord(db, queueRecordId);

    if (!raw.ok) return { ok: false, reason: "storage_unavailable" };
    if (raw.value === null) return { ok: false, reason: "not_found" };

    const parsed = readQueuedSale(raw.value);

    if (!parsed.ok) return { ok: false, reason: "corrupt_record" };

    const moved = transitionQueuedSale(parsed.record, "synced", now);

    if (!moved.ok) return { ok: false, reason: "illegal_transition" };

    const synced: QueuedSale = {
      ...moved.record,
      serverOrderId: receipt.orderId,
      serverOrderNumber: receipt.orderNumber,
      serverCreatedAt: receipt.createdAt,
      nextAttemptAt: null,
      lastErrorCode: null,
      lastErrorMessage: null,
    };

    const written = await putQueuedSale(db, synced);

    return written.ok ? { ok: true, value: synced } : { ok: false, reason: "write_failed" };
  });
}

