// Feature 24.5C — the queue's public API: storage I/O plus the pure rules.
//
// Thin by design, like lib/deviceOfflineSession.ts. Every rule lives in
// lib/saleQueue.ts and every byte of I/O in lib/deviceOfflineStore.ts; this
// module owns the small amount of glue between them, so there is no third place
// for a rule to hide.
//
// NOTHING HERE TALKS TO THE NETWORK. 24.5C persists sale intents and nothing
// else — no submission, no retry loop, no complete_sale_v4 call. 24.5D adds
// that on top of this floor. The offline checkout fence from 24.5A is untouched
// and nothing in the app calls enqueueSale yet.
//
// SECURITY, stated once: a queued record holds item ids, quantities, modifier
// selections, a "cash"/"card" LABEL and timestamps. It holds no card number, no
// CVV, no expiry, no cardholder name and no track data — POS Canvas never
// receives any of those, so there is nothing to store. It holds no Supabase
// key, no service-role credential and no session token; the device's auth
// session stays where it already was, in the Supabase client's own storage.
// lib/offlineQueue.guards.test.ts asserts every one of those.
