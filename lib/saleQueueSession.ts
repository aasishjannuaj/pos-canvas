export type QueueFailure =
  | "storage_unavailable"
  | "write_failed"
  | "duplicate_sale_request"
  | "not_found"
  | "corrupt_record"
  | "illegal_transition";

export type QueueResult<T> = { ok: true; value: T } | { ok: false; reason: QueueFailure };

/** A record that failed validation on read, kept visible rather than dropped. */
export type QuarantinedSale = { queueRecordId: string | null; reason: QueueReadFailure };

async function withDb<T>(
  run: (db: IDBDatabase) => Promise<QueueResult<T>>
): Promise<QueueResult<T>> {
  const opened = await openOfflineDb();

  if (!opened.ok) {
    return { ok: false, reason: "storage_unavailable" };
  }

  try {
    return await run(opened.value);
  } finally {
    opened.value.close();
  }
}

