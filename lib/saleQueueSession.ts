export type EnqueueSaleInput = {
  /** Generated by the CALLER, before this function is reached. See below. */
  saleRequestId: string;
  queueRecordId: string;
  deviceAuthUserId: string;
  deviceId: string;
  projectId: string;
  buildJobId: string;
  paymentMethod: PaymentMethod;
  items: QueuedSaleItem[];
  occurredAt: string;
  now: string;
  /**
   * v1.3 Feature 1B — the historical attribution claims, or null.
   *
   * OPTIONAL ON THE INPUT so every existing caller and test compiles unchanged;
   * the record always stores an explicit null rather than an absent key.
   */
  employeePosSessionId?: string | null;
  registerSessionId?: string | null;
  /**
   * G-1-CLIENT-1 — present only for a sale transferred from an uncertain online
   * attempt. The record is then written as a STRICT-RECOVERY record: its claims
   * and its occurredAt are the originals, taken from here and from nowhere else,
   * and it can only ever be submitted through complete_sale_recovery_v1.
   */
  strictRecovery?: StrictRecoveryClaims;
};

/**
 * Persists a sale intent. The ONLY way a record enters the queue.
 *
 * THE IDEMPOTENCY KEY IS AN INPUT, NOT SOMETHING THIS FUNCTION MINTS. That is
 * the whole point of 24.5C: the caller generates the saleRequestId, and this
 * function makes it durable in the same transaction as the record. Once this
 * returns ok, the key exists on disk and every future retry — after a reload,
 * an app restart, a process kill — reuses it. A function that generated its own
 * key would produce a new one each time it was called, which is exactly how a
 * crash-and-retry becomes two sales.
 *
 * ENQUEUE IS ALL-OR-NOTHING. `add` (not `put`) plus the unique index on
 * saleRequestId means the storage engine itself refuses a second record for one
 * sale. A failure returns a clear reason and the caller must treat the sale as
 * NOT queued — there is no partial success, and no in-memory or localStorage
 * fallback for a financial record.
 */
export async function enqueueSale(input: EnqueueSaleInput): Promise<QueueResult<QueuedSale>> {
  const strict = input.strictRecovery ?? null;

  const record: QueuedSale = {
    queueSchemaVersion: SALE_QUEUE_SCHEMA_VERSION,
    requestPayloadVersion: strict !== null ? STRICT_RECOVERY_PAYLOAD_VERSION : SALE_REQUEST_PAYLOAD_VERSION,
    queueRecordId: input.queueRecordId,
    saleRequestId: input.saleRequestId,
    deviceAuthUserId: input.deviceAuthUserId,
    deviceId: input.deviceId,
    projectId: input.projectId,
    buildJobId: input.buildJobId,
    paymentMethod: input.paymentMethod,
    // Devices may not tip. complete_sale_v4 rejects a non-zero device tip, so a
    // record carrying one could never be submitted.
    tipAmount: 0,
    items: input.items,
    // G-1-CLIENT-1 — a strict record happened when it was FIRST attempted.
    occurredAt: strict !== null ? strict.originalAttemptAt : input.occurredAt,
    source: "offline_queued",
    state: "pending",
    queuedAt: input.now,
    updatedAt: input.now,
    attemptCount: 0,
    lastAttemptAt: null,
    nextAttemptAt: null,
    lastErrorCode: null,
    lastErrorMessage: null,
    serverOrderId: null,
    serverOrderNumber: null,
    serverCreatedAt: null,
    // Claims only. The server decides whether it can prove them; a sale is
    // never refused for lacking them.
    //
    // G-1-CLIENT-1 — except on a strict record, where they are the ORIGINALS
    // and the server refuses the whole sale rather than store anything else.
    employeePosSessionId:
      strict !== null ? strict.originalEmployeePosSessionId : input.employeePosSessionId ?? null,
    registerSessionId:
      strict !== null ? strict.originalRegisterSessionId : input.registerSessionId ?? null,
    ...(strict !== null ? { strictRecovery: { ...strict } } : {}),
  };

  // Validated BEFORE it is written, using the same reader that guards every
  // load. A record that could not be read back is a record that must not be
  // written: it would sit in the queue forever, unsubmittable.
  const validated = readQueuedSale(record);

  if (!validated.ok) {
    return { ok: false, reason: "corrupt_record" };
  }

  return withDb(async (db) => {
    const existing = await readQueuedSaleByRequestId(db, input.saleRequestId);

    if (existing.ok && existing.value !== null) {
      return { ok: false, reason: "duplicate_sale_request" };
    }

    const written = await insertQueuedSale(db, validated.record);

    // The unique index is the authority here; this pre-check is a courtesy that
    // produces a better reason code. A constraint violation reaching this point
    // still means the same thing: the sale is already queued.
    if (!written.ok) {
      return { ok: false, reason: "duplicate_sale_request" };
    }

    return { ok: true, value: validated.record };
  });
}

