export type QueueRecoveryReport = {
  recovered: number;
  quarantined: number;
  summary: QueueSummary;
};

/**
 * Returns any record stranded in `syncing` to `pending`.
 *
 * Runs at queue initialization. A process that dies mid-submission leaves a
 * record claiming to be in flight with nothing flying it; without this it would
 * sit there forever, invisible to a work list that only reads `pending`.
 *
 * Safe because of server-side idempotency, not because of optimism: the
 * interrupted submission carried this record's saleRequestId, and
 * complete_sale_v4 resolves that key before allocating an order number,
 * mutating inventory or writing an audit row. Retrying therefore either creates
 * the sale or returns the one already created. See recoverInterruptedSale.
 */
export async function recoverInterruptedSyncs(now: string): Promise<QueueResult<QueueRecoveryReport>> {
  const listing = await listQueuedSales();

  if (!listing.ok) return listing;

  const stranded = listing.value.sales.filter((sale) => sale.state === "syncing");

  if (stranded.length === 0) {
    return {
      ok: true,
      value: {
        recovered: 0,
        quarantined: listing.value.quarantined.length,
        summary: summarizeQueue(listing.value.sales),
      },
    };
  }

  const written = await withDb(async (db) => {
    for (const sale of stranded) {
      const result = await putQueuedSale(db, recoverInterruptedSale(sale, now));

      if (!result.ok) return { ok: false as const, reason: "write_failed" as const };
    }

    return { ok: true as const, value: undefined };
  });

  if (!written.ok) return written;

  const after = await listQueuedSales();

  return after.ok
    ? {
        ok: true,
        value: {
          recovered: stranded.length,
          quarantined: after.value.quarantined.length,
          summary: summarizeQueue(after.value.sales),
        },
      }
    : after;
}
